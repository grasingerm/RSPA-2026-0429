def _validate_configuration_collection(configurations: Sequence[Sequence[Any]]) -> None:
    if not isinstance(configurations, (list, tuple)):
        raise TypeError("configurations must be a list of [alpha1, rk, states] lists.")

    for group_index, configuration in enumerate(configurations, start=1):
        if not isinstance(configuration, (list, tuple)) or len(configuration) != 3:
            raise ValueError(
                f"Configuration {group_index} must be [alpha1, rk, fold_angle_tuples]."
            )
        alpha1, rk, states = configuration
        if not np.isscalar(alpha1) or not np.isscalar(rk):
            raise TypeError(
                f"Configuration {group_index}: alpha1 and rk must be scalars."
            )
        if not isinstance(states, (list, tuple)):
            raise TypeError(
                f"Configuration {group_index}: third element must be a list of "
                "fold-angle tuples."
            )


def run_degree8_batch(
    configurations: Sequence[Sequence[Any]],
    *,
    output_directory: Path | str | None = DEFAULT_OUTPUT_DIRECTORY,
    finite_difference_steps: Sequence[float] = FINITE_DIFFERENCE_STEPS,
    primary_step: float = PRIMARY_FINITE_DIFFERENCE_STEP,
    input_closure_tolerance: float = INPUT_CLOSURE_TOLERANCE,
    input_symmetry_tolerance: float = INPUT_SYMMETRY_TOLERANCE,
    gradient_tolerance: float = GRADIENT_TOLERANCE,
    eigenvalue_tolerance: float = EIGENVALUE_TOLERANCE,
    retraction_closure_tolerance: float = RETRACTION_CLOSURE_TOLERANCE,
    write_files: bool = True,
    print_diagnostics: bool = True,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    """Run full-space stability diagnostics over the nested configuration list."""
    _validate_configuration_collection(configurations)

    steps = tuple(float(step) for step in finite_difference_steps)
    if not steps or any((not np.isfinite(step) or step <= 0.0) for step in steps):
        raise ValueError("finite_difference_steps must contain positive finite values.")
    if primary_step <= 0.0 or not np.isfinite(primary_step):
        raise ValueError("primary_step must be positive and finite.")

    summaries: list[dict[str, Any]] = []
    per_step_rows: list[dict[str, Any]] = []
    details: list[dict[str, Any]] = []

    for group_index, configuration in enumerate(configurations, start=1):
        alpha1_raw, rk_raw, fold_angle_states = configuration
        alpha1 = float(alpha1_raw)
        rk = float(rk_raw)

        for state_index, fold_angles in enumerate(fold_angle_states, start=1):
            try:
                summary, rows, detail = analyze_one_state(
                    group_index=group_index,
                    state_index=state_index,
                    alpha1=alpha1,
                    rk=rk,
                    fold_angles=fold_angles,
                    finite_difference_steps=steps,
                    primary_step=primary_step,
                    input_closure_tolerance=input_closure_tolerance,
                    input_symmetry_tolerance=input_symmetry_tolerance,
                    gradient_tolerance=gradient_tolerance,
                    eigenvalue_tolerance=eigenvalue_tolerance,
                    retraction_closure_tolerance=retraction_closure_tolerance,
                )
            except Exception as exc:
                state_id = f"cfg_{group_index:02d}_state_{state_index:03d}"
                summary = {
                    "state_id": state_id,
                    "group_index": group_index,
                    "state_index": state_index,
                    "alpha1_rad": alpha1,
                    "alpha1_over_pi": alpha1 / np.pi,
                    "rk": rk,
                    "consensus_status": "analysis_error",
                    "primary_status": "analysis_error",
                    "interpretation": _status_interpretation("analysis_error"),
                    "successful_step_count": 0,
                    "tested_step_count": len(steps),
                    "certified_relaxed_survivor": False,
                    "primary_error": f"{type(exc).__name__}: {exc}",
                }
                rows = []
                detail = {
                    **summary,
                    "raw_fold_angles": list(fold_angles)
                    if isinstance(fold_angles, Iterable)
                    else repr(fold_angles),
                }

            summaries.append(summary)
            per_step_rows.extend(rows)
            details.append(detail)

    group_summaries = build_group_summaries(summaries)

    if print_diagnostics:
        print_summary_table(summaries)
        print_group_summary(group_summaries)
        print_global_summary(summaries)

    if write_files:
        output_path = Path(output_directory or DEFAULT_OUTPUT_DIRECTORY)
        output_path.mkdir(parents=True, exist_ok=True)
        write_csv(output_path / "degree8_stability_summary.csv", summaries)
        write_csv(output_path / "degree8_stability_by_step.csv", per_step_rows)
        write_csv(output_path / "degree8_stability_by_configuration.csv", group_summaries)
        with (output_path / "degree8_stability_details.json").open(
            "w", encoding="utf-8"
        ) as handle:
            json.dump(_to_builtin(details), handle, indent=2, allow_nan=False)

        if print_diagnostics:
            print(f"\nWrote diagnostics to: {output_path.resolve()}")

    return summaries, per_step_rows, details


def _scalar_csv_row(row: dict[str, Any]) -> dict[str, Any]:
    """Drop large arrays from CSV and serialize small arrays compactly."""
    excluded = {
        "phi",
        "stiffness",
        "rest_angles",
        "deformed_creases",
        "full_reduced_hessian",
        "full_eigenvectors_q",
        "symmetric_hessian",
        "breaking_hessian",
        "coupling_hessian",
    }
    converted: dict[str, Any] = {}
    for key, value in row.items():
        if key in excluded:
            continue
        if isinstance(value, np.ndarray):
            converted[key] = json.dumps(value.tolist())
        elif isinstance(value, (list, tuple)):
            converted[key] = json.dumps(_to_builtin(value))
        elif isinstance(value, np.generic):
            converted[key] = value.item()
        else:
            converted[key] = value
    return converted


def write_csv(path: Path, rows: Sequence[dict[str, Any]]) -> None:
    """Write heterogeneous dictionary rows to CSV with stable column ordering."""
    if not rows:
        path.write_text("", encoding="utf-8")
        return

    scalar_rows = [_scalar_csv_row(row) for row in rows]
    preferred = [
        "state_id",
        "group_index",
        "state_index",
        "alpha1_rad",
        "alpha1_over_pi",
        "rk",
        "finite_difference_step",
        "consensus_status",
        "primary_status",
        "status",
        "certified_relaxed_survivor",
        "closure_norm",
        "symmetry_norm",
        "constraint_rank",
        "tangent_dimension",
        "symmetric_dimension",
        "breaking_dimension",
        "compatibility_condition_number",
        "full_gradient_norm",
        "symmetric_gradient_norm",
        "breaking_gradient_norm",
        "minimum_full_eigenvalue",
        "minimum_symmetric_eigenvalue",
        "minimum_breaking_eigenvalue",
        "coupling_hessian_norm",
    ]
    keys = {key for row in scalar_rows for key in row}
    fieldnames = [key for key in preferred if key in keys]
    fieldnames.extend(sorted(keys.difference(fieldnames)))

    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(scalar_rows)


def _format_float(value: Any, width: int = 11) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "-".rjust(width)
    if not math.isfinite(number):
        return "-".rjust(width)
    return f"{number:.3e}".rjust(width)


def print_summary_table(summaries: Sequence[dict[str, Any]]) -> None:
    """Print one compact diagnostics line per candidate."""
    if not summaries:
        print("No candidate states were supplied in CONFIGURATIONS.")
        return

    header = (
        f"{'state':<20} {'a1/pi':>8} {'rk':>10} {'closure':>11} {'sym':>11} "
        f"{'|g|':>11} {'|gb|':>11} {'lam_min':>11} {'lam_b,min':>11} "
        f"{'consensus':<26}"
    )
    print(header)
    print("-" * len(header))

    for row in summaries:
        print(
            f"{str(row.get('state_id', '-')):<20} "
            f"{float(row.get('alpha1_over_pi', math.nan)):>8.4f} "
            f"{float(row.get('rk', math.nan)):>10.3e} "
            f"{_format_float(row.get('closure_norm'))} "
            f"{_format_float(row.get('symmetry_norm'))} "
            f"{_format_float(row.get('primary_full_gradient_norm'))} "
            f"{_format_float(row.get('primary_breaking_gradient_norm'))} "
            f"{_format_float(row.get('primary_minimum_full_eigenvalue'))} "
            f"{_format_float(row.get('primary_minimum_breaking_eigenvalue'))} "
            f"{str(row.get('consensus_status', '-')):<26}"
        )
        error = str(row.get("primary_error", "") or "")
        if error:
            print(f"    error: {error}")
        if (
            row.get("expected_dimension_check") is False
            and row.get("constraint_rank") == 3
        ):
            print(
                "    warning: expected regular degree-8 dimensions are "
                "tangent=5, symmetric=2, breaking=3; inspect closure precision."
            )


def print_global_summary(summaries: Sequence[dict[str, Any]]) -> None:
    """Print total counts and the relaxed-space lower-bound count."""
    if not summaries:
        return

    counts = Counter(str(row.get("consensus_status", "unknown")) for row in summaries)
    survivors = sum(bool(row.get("certified_relaxed_survivor", False)) for row in summaries)

    print("\nClassification counts")
    print("---------------------")
    for status, count in sorted(counts.items()):
        print(f"{status:<28} {count:>4d}")
    print(f"{'total candidates':<28} {len(summaries):>4d}")
    print(f"{'certified relaxed survivors':<28} {survivors:>4d}")
    print(
        "\nThe certified-survivor count is a lower bound on the number of "
        "physically stable states when unilateral contact is restored."
    )


def build_group_summaries(summaries: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    """Aggregate state classifications by the input [alpha1, rk, states] group."""
    grouped: dict[int, list[dict[str, Any]]] = {}
    for row in summaries:
        grouped.setdefault(int(row["group_index"]), []).append(row)

    output: list[dict[str, Any]] = []
    statuses = [
        "strict_local_minimum",
        "saddle",
        "not_stationary",
        "marginal_or_inconclusive",
        "singular_configuration",
        "step_sensitive",
        "input_not_compatible",
        "input_not_symmetric",
        "analysis_error",
    ]
    for group_index, rows in sorted(grouped.items()):
        counts = Counter(str(row.get("consensus_status", "unknown")) for row in rows)
        output.append(
            {
                "group_index": group_index,
                "alpha1_rad": rows[0].get("alpha1_rad", math.nan),
                "alpha1_over_pi": rows[0].get("alpha1_over_pi", math.nan),
                "rk": rows[0].get("rk", math.nan),
                "symmetric_candidate_upper_bound": len(rows),
                "relaxed_survivor_lower_bound": sum(
                    bool(row.get("certified_relaxed_survivor", False)) for row in rows
                ),
                **{f"n_{status}": counts.get(status, 0) for status in statuses},
            }
        )
    return output


def print_group_summary(group_rows: Sequence[dict[str, Any]]) -> None:
    """Print upper/lower state-count bounds for each (alpha1, rk) panel."""
    if not group_rows:
        return
    print("\nPer-configuration bounds")
    print("------------------------")
    print(
        f"{'group':>5} {'a1/pi':>8} {'rk':>10} {'lower':>7} {'upper':>7} "
        f"{'saddle':>7} {'1st-order':>10} {'marginal':>9} {'errors':>7}"
    )
    for row in group_rows:
        errors = (
            int(row.get("n_analysis_error", 0))
            + int(row.get("n_input_not_compatible", 0))
            + int(row.get("n_input_not_symmetric", 0))
            + int(row.get("n_step_sensitive", 0))
        )
        print(
            f"{int(row['group_index']):>5d} "
            f"{float(row['alpha1_over_pi']):>8.4f} "
            f"{float(row['rk']):>10.3e} "
            f"{int(row['relaxed_survivor_lower_bound']):>7d} "
            f"{int(row['symmetric_candidate_upper_bound']):>7d} "
            f"{int(row.get('n_saddle', 0)):>7d} "
            f"{int(row.get('n_not_stationary', 0)):>10d} "
            f"{int(row.get('n_marginal_or_inconclusive', 0)):>9d} "
            f"{errors:>7d}"
        )


