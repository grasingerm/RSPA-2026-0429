def analyze_one_state(
    *,
    group_index: int,
    state_index: int,
    alpha1: float,
    rk: float,
    fold_angles: Sequence[float],
    finite_difference_steps: Sequence[float],
    primary_step: float,
    input_closure_tolerance: float,
    input_symmetry_tolerance: float,
    gradient_tolerance: float,
    eigenvalue_tolerance: float,
    retraction_closure_tolerance: float,
) -> tuple[dict[str, Any], list[dict[str, Any]], dict[str, Any]]:
    """Analyze one candidate and return summary, per-step rows, and details."""
    state_id = f"cfg_{group_index:02d}_state_{state_index:03d}"
    phi, input_format = expand_fold_angles(fold_angles)

    B = crease_vectors_degree8(alpha1)
    stiffness, rest_angles = degree8_material_parameters(alpha1, rk)
    symmetry_matrix = symmetry_equalities_degree8()

    closure_vector = closure_residual(B, phi)
    closure_norm = _norm(closure_vector)
    symmetry_vector = symmetry_matrix @ phi
    symmetry_norm = _norm(symmetry_vector)
    energy = torsional_energy(phi, stiffness, rest_angles)

    base: dict[str, Any] = {
        "state_id": state_id,
        "group_index": group_index,
        "state_index": state_index,
        "alpha1_rad": float(alpha1),
        "alpha1_over_pi": float(alpha1 / np.pi),
        "rk": float(rk),
        "input_format": input_format,
        "phi": phi,
        "stiffness": stiffness,
        "rest_angles": rest_angles,
        "energy_at_supplied_state": energy,
        "closure_vector": closure_vector,
        "closure_norm": closure_norm,
        "symmetry_vector": symmetry_vector,
        "symmetry_norm": symmetry_norm,
        **{f"phi{i + 1}": float(phi[i]) for i in range(8)},
    }

    if closure_norm > input_closure_tolerance:
        summary = {
            **base,
            "consensus_status": "input_not_compatible",
            "primary_status": "input_not_compatible",
            "interpretation": _status_interpretation("input_not_compatible"),
            "successful_step_count": 0,
            "tested_step_count": len(finite_difference_steps),
            "certified_relaxed_survivor": False,
        }
        details = {**base, "runs": [], "error": summary["interpretation"]}
        return summary, [], details

    if symmetry_norm > input_symmetry_tolerance:
        summary = {
            **base,
            "consensus_status": "input_not_symmetric",
            "primary_status": "input_not_symmetric",
            "interpretation": _status_interpretation("input_not_symmetric"),
            "successful_step_count": 0,
            "tested_step_count": len(finite_difference_steps),
            "certified_relaxed_survivor": False,
        }
        details = {**base, "runs": [], "error": summary["interpretation"]}
        return summary, [], details

    # Independent geometric diagnostics at the supplied state.
    spaces = tangent_spaces(
        B,
        phi,
        closure_tolerance=max(input_closure_tolerance, closure_norm * 10.0 + 1.0e-14),
    )
    singular_values = spaces.singular_values
    positive_singular_values = singular_values[singular_values > 1.0e-14]
    jacobian_condition_number = (
        float(positive_singular_values[0] / positive_singular_values[-1])
        if positive_singular_values.size >= 2
        else math.inf
    )
    deformed_creases = forward_kinematics(B, phi).deformed_creases

    base.update(
        {
            "constraint_rank": spaces.rank,
            "tangent_dimension": spaces.tangent_basis.shape[1],
            "compatibility_singular_values": singular_values,
            "compatibility_condition_number": jacobian_condition_number,
            "deformed_creases": deformed_creases,
        }
    )

    per_step_rows: list[dict[str, Any]] = []
    detailed_runs: list[dict[str, Any]] = []

    for step in finite_difference_steps:
        run_base = {
            "state_id": state_id,
            "group_index": group_index,
            "state_index": state_index,
            "alpha1_rad": float(alpha1),
            "alpha1_over_pi": float(alpha1 / np.pi),
            "rk": float(rk),
            "finite_difference_step": float(step),
            "closure_norm": closure_norm,
            "symmetry_norm": symmetry_norm,
            "constraint_rank": spaces.rank,
            "compatibility_condition_number": jacobian_condition_number,
        }

        try:
            result = analyze_symmetry_breaking(
                B,
                phi,
                stiffness,
                rest_angles,
                symmetry_matrix,
                finite_difference_step=float(step),
                gradient_tolerance=gradient_tolerance,
                eigenvalue_tolerance=eigenvalue_tolerance,
                closure_tolerance=retraction_closure_tolerance,
            )
            full = result.full_result
            symmetric_eigenvalues = _eigenvalues_symmetric(result.symmetric_hessian)

            row = {
                **run_base,
                "status": full.status,
                "analysis_succeeded": True,
                "error": "",
                "energy_after_q0_retraction": full.energy,
                "energy_projection_change": full.energy - energy,
                "full_gradient_norm": _norm(full.reduced_gradient),
                "symmetric_gradient_norm": _norm(result.symmetric_gradient),
                "breaking_gradient_norm": _norm(result.breaking_gradient),
                "minimum_full_eigenvalue": _smallest(full.eigenvalues),
                "minimum_symmetric_eigenvalue": _smallest(symmetric_eigenvalues),
                "minimum_breaking_eigenvalue": _smallest(result.breaking_eigenvalues),
                "maximum_abs_full_eigenvalue": _largest_abs(full.eigenvalues),
                "coupling_hessian_norm": _matrix_norm(result.coupling_hessian),
                "symmetric_dimension": result.symmetric_dimension,
                "breaking_dimension": result.breaking_dimension,
            }
            per_step_rows.append(row)

            detailed_runs.append(
                {
                    **row,
                    "full_reduced_gradient": full.reduced_gradient,
                    "full_reduced_hessian": full.reduced_hessian,
                    "full_eigenvalues": full.eigenvalues,
                    "full_eigenvectors_q": full.eigenvectors_q,
                    "symmetric_gradient": result.symmetric_gradient,
                    "breaking_gradient": result.breaking_gradient,
                    "symmetric_hessian": result.symmetric_hessian,
                    "symmetric_eigenvalues": symmetric_eigenvalues,
                    "breaking_hessian": result.breaking_hessian,
                    "breaking_eigenvalues": result.breaking_eigenvalues,
                    "coupling_hessian": result.coupling_hessian,
                    "most_unstable_full_fold_mode": full.most_unstable_fold_mode,
                    "most_unstable_breaking_fold_mode": (
                        result.most_unstable_breaking_fold_mode
                    ),
                }
            )
        except Exception as exc:  # keep the batch alive and expose the failure
            row = {
                **run_base,
                "status": "analysis_error",
                "analysis_succeeded": False,
                "error": f"{type(exc).__name__}: {exc}",
                "energy_after_q0_retraction": math.nan,
                "energy_projection_change": math.nan,
                "full_gradient_norm": math.nan,
                "symmetric_gradient_norm": math.nan,
                "breaking_gradient_norm": math.nan,
                "minimum_full_eigenvalue": math.nan,
                "minimum_symmetric_eigenvalue": math.nan,
                "minimum_breaking_eigenvalue": math.nan,
                "maximum_abs_full_eigenvalue": math.nan,
                "coupling_hessian_norm": math.nan,
                "symmetric_dimension": math.nan,
                "breaking_dimension": math.nan,
            }
            per_step_rows.append(row)
            detailed_runs.append(row)

    successful_rows = [row for row in per_step_rows if row["analysis_succeeded"]]
    successful_statuses = [str(row["status"]) for row in successful_rows]

    if not successful_statuses:
        consensus_status = "analysis_error"
    elif len(set(successful_statuses)) == 1:
        consensus_status = successful_statuses[0]
    else:
        consensus_status = "step_sensitive"

    # Select the primary row exactly when available; otherwise use the nearest
    # successful finite-difference step.
    primary_candidates = [
        row
        for row in successful_rows
        if math.isclose(
            float(row["finite_difference_step"]),
            float(primary_step),
            rel_tol=0.0,
            abs_tol=max(1.0e-16, 1.0e-12 * abs(primary_step)),
        )
    ]
    if primary_candidates:
        primary = primary_candidates[0]
    elif successful_rows:
        primary = min(
            successful_rows,
            key=lambda row: abs(float(row["finite_difference_step"]) - primary_step),
        )
    else:
        primary = {
            "status": "analysis_error",
            "finite_difference_step": math.nan,
            "full_gradient_norm": math.nan,
            "symmetric_gradient_norm": math.nan,
            "breaking_gradient_norm": math.nan,
            "minimum_full_eigenvalue": math.nan,
            "minimum_symmetric_eigenvalue": math.nan,
            "minimum_breaking_eigenvalue": math.nan,
            "coupling_hessian_norm": math.nan,
            "symmetric_dimension": math.nan,
            "breaking_dimension": math.nan,
            "error": "All finite-difference analyses failed.",
        }

    full_minima = [
        float(row["minimum_full_eigenvalue"])
        for row in successful_rows
        if math.isfinite(float(row["minimum_full_eigenvalue"]))
    ]
    breaking_minima = [
        float(row["minimum_breaking_eigenvalue"])
        for row in successful_rows
        if math.isfinite(float(row["minimum_breaking_eigenvalue"]))
    ]

    summary = {
        **base,
        "consensus_status": consensus_status,
        "primary_status": primary["status"],
        "interpretation": _status_interpretation(consensus_status),
        "primary_finite_difference_step": primary["finite_difference_step"],
        "successful_step_count": len(successful_rows),
        "tested_step_count": len(finite_difference_steps),
        "primary_full_gradient_norm": primary["full_gradient_norm"],
        "primary_symmetric_gradient_norm": primary["symmetric_gradient_norm"],
        "primary_breaking_gradient_norm": primary["breaking_gradient_norm"],
        "primary_minimum_full_eigenvalue": primary["minimum_full_eigenvalue"],
        "primary_minimum_symmetric_eigenvalue": primary[
            "minimum_symmetric_eigenvalue"
        ],
        "primary_minimum_breaking_eigenvalue": primary[
            "minimum_breaking_eigenvalue"
        ],
        "primary_coupling_hessian_norm": primary["coupling_hessian_norm"],
        "symmetric_dimension": primary["symmetric_dimension"],
        "breaking_dimension": primary["breaking_dimension"],
        "full_minimum_eigenvalue_range": (
            max(full_minima) - min(full_minima) if len(full_minima) >= 2 else 0.0
        ),
        "breaking_minimum_eigenvalue_range": (
            max(breaking_minima) - min(breaking_minima)
            if len(breaking_minima) >= 2
            else 0.0
        ),
        "expected_dimension_check": (
            spaces.rank == 3
            and spaces.tangent_basis.shape[1] == 5
            and primary["symmetric_dimension"] == 2
            and primary["breaking_dimension"] == 3
        ),
        "status_by_step": "; ".join(
            f"{float(row['finite_difference_step']):.3e}:{row['status']}"
            for row in per_step_rows
        ),
        "certified_relaxed_survivor": (
            consensus_status == "strict_local_minimum"
            and len(successful_rows) == len(finite_difference_steps)
        ),
        "primary_error": primary.get("error", ""),
    }

    details = {**base, "summary": summary, "runs": detailed_runs}
    return summary, per_step_rows, details


