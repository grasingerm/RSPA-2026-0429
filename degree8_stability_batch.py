def degree8_material_parameters(
    alpha1: float,
    rk: float,
) -> tuple[FloatArray, FloatArray]:
    """Return crease stiffnesses and rest angles used in Section 3(b)."""
    if not np.isfinite(alpha1) or not (0.0 < alpha1 < 0.5 * np.pi):
        raise ValueError(
            f"alpha1 must satisfy 0 < alpha1 < pi/2; got {alpha1!r}."
        )
    if not np.isfinite(rk) or rk <= 0.0:
        raise ValueError(f"rk must be finite and positive; got {rk!r}.")

    phi_m = -np.pi / 2.0
    phi_v = np.pi / 2.0
    rest_angles = np.array(
        [phi_m, phi_v, phi_m, phi_v, phi_m, phi_v, phi_m, phi_v],
        dtype=float,
    )

    k_m = 0.025 * np.sqrt(rk)
    k_v = 0.025 / np.sqrt(rk)
    stiffness = np.where(rest_angles < 0.0, k_m, k_v)
    return stiffness, rest_angles


def expand_fold_angles(fold_angles: Sequence[float]) -> tuple[FloatArray, str]:
    """Convert a compact or full fold-angle tuple to a full eight-angle vector."""
    values = np.asarray(fold_angles, dtype=float).reshape(-1)
    if not np.all(np.isfinite(values)):
        raise ValueError("fold-angle tuple contains non-finite entries.")

